def sval(st, *names):
    """按顺序找第一个存在的统计字段；OpenMV 5.0 里是属性、4.x 里是方法 —— 两种都吃。"""
    for nm in names:
        try:
            v = getattr(st, nm)
            return v() if callable(v) else v
        except Exception:
            pass
    raise Exception("统计字段都没有: %s" % (names,))


def lsq(pts):
    """最小二乘。线接近水平，row 当因变量才良态。返回 (斜率, 截距, 残差RMS)。"""
    n = len(pts)
    sx = sum(p[0] for p in pts)
    sy = sum(p[1] for p in pts)
    sxx = sum(p[0] * p[0] for p in pts)
    sxy = sum(p[0] * p[1] for p in pts)
    d = n * sxx - sx * sx
    if d == 0:
        return None
    m = (n * sxy - sx * sy) / d
    c = (sy * sxx - sx * sxy) / d
    e = math.sqrt(sum((p[1] - (m * p[0] + c)) ** 2 for p in pts) / n)
    return m, c, e


def smooth3(v):
    """三点滑动平均（首尾各取两点平均）。**标准赛道浅色差专用（2026-09-27 第九次）**：
    两面色差浅时，条均值的色度噪声和两面色差同量级，f 剖面会被噪声揉出假过零、
    或让真过零位置逐帧抖动。单调过渡的过零位置不受此平滑偏置（线性斜坡的零点
    不动），白噪声方差 ↓~3 倍 —— 信噪比净赚。只作用于找穿越的判别量，不动参考
    色、不动出量。"""
    n = len(v)
    if n < 3:
        return v[:]
    out = [0.0] * n
    out[0] = (v[0] + v[1]) / 2.0
    out[n - 1] = (v[n - 2] + v[n - 1]) / 2.0
    for j in range(1, n - 1):
        out[j] = (v[j - 1] + v[j] + v[j + 1]) / 3.0
    return out


def col_profile(img, x):
    """该列的纵向剖面: [(行中心, a均值, b均值, L均值), ...]，从上到下。
    a、b 都要：判别在调用侧用"到上下参考色的距离²之差"做（见主循环第 3 步）——
    固定曝光下阴影会把单通道和黑条一起压向 0，单通道分不开"阴影边"和"真边界"。
    用 mean 不用 median：穿过交界那条横条里 median 会偏向多数那一侧，交点会"跳格"。"""
    out = []
    x0 = x - COL_W // 2
    for j in range(NSTRIP):
        y0 = WIN_Y[0] + j * STRIP
        st = img.get_statistics(roi=(x0, y0, COL_W, STRIP))
        out.append((y0 + STRIP / 2.0,
                    sval(st, 'a_mean', 'a_median'),
                    sval(st, 'b_mean', 'b_median'),
                    sval(st, 'l_mean', 'l_median')))
    return out


def cross_row(prof, mid, min_swing, dead=None):
    """找剖面穿过 mid 的那一行（主循环喂的是"到上下参考色距离²之差 f"，mid=0）。
    一列里可能穿越多次（远处那道弧、反光、褶皱阴影边），
    取**邻域总落差最大**的那一次 —— 真正的材质交界落差最大。
    落差不足 min_swing 的一律不认（宁可这一列没点，也别塞个假的）。
    dead=连顶黑区掩码（True 的条在"从窗口顶连下来的暗条串"里，补光死角本体）：
    贴着它的穿越是 黑↔亮 过渡、不是材质交界 —— 两边黑区极值的源头，一律不认。
    练习图的黑线是悬在亮区里的 1~2 条、不连顶，不受此规则影响。"""
    best_row, best_swing = None, 0.0
    n = len(prof)
    for j in range(n - 1):
        if dead is not None and (dead[j] or dead[j + 1]):
            continue
        b0, b1 = prof[j][1], prof[j + 1][1]
        if (b0 - mid) * (b1 - mid) <= 0 and abs(b1 - b0) > 1e-6:
            seg = [prof[k][1] for k in range(max(0, j - CROSS_SWING_DEPTH),
                                             min(n, j + 2 + CROSS_SWING_DEPTH))]
            swing = max(seg) - min(seg)
            if swing > best_swing:
                best_swing = swing
                best_row = prof[j][0] + (mid - b0) / (b1 - b0) * STRIP
    if best_row is None or best_swing < min_swing:
        return None
    return best_row


def refine_local(prof, r0, dark=None, dead=None):
    """第二遍细化：用粗定位行 r0 两侧近处的条带做局部参考色，重算穿越行。
    为什么：顶/底参考取自画面最上/最下，会被"远端阴影"(顶部)和"LED 过曝"(底部)
    逐列污染 —— 结果.bmp 帧：底部参考 b 从 -10(过曝中心) 漂到 -37(边缘饱和)，
    顶部参考吃进左上阴影。距离剖面的过零点在宽黑带里的高度由 |上参考|/|下参考|
    的比值决定，比值逐列变 → 过零点排成 ±15px 的拱形(旧法新法同病，实测同帧
    逐列差 ≤0.5px)。换成交界两侧近处的参考(同帧同光照，各列一致)，过零点锚定
    在黑带附近的同一相对位置 → 拱形消失；绝对位置的整体平移由 TARGET_OFFSET 吸收。
    只用已采样的 prof，不加 get_statistics，不掉 fps。
    隔 1 条、取 2 条(j0±2,±3)：黑带约 1~2 条厚，参考必须落在带外的实色上；
    粗定位拱形 ≤±2 条时参考仍落在正确一侧。
    dark/dead（2026-09-27）：暗条不进局部参考（色度已死，进去就把参考染黑）；
    连顶黑区里的穿越按 cross_row 同一规则不认。局部参考被暗条滤到不足 2 条 →
    返回 None，保留粗定位行。"""
    j0 = int((r0 - WIN_Y[0]) / STRIP)
    def mean2(js):
        js = [j for j in js
              if 0 <= j < NSTRIP and not (dark is not None and dark[j])]
        if len(js) < 2:
            return None
        return (sum(prof[j][1] for j in js) / len(js),
                sum(prof[j][2] for j in js) / len(js))
    t = mean2([j0 - 3, j0 - 2])
    b = mean2([j0 + 2, j0 + 3])
    if t is None or b is None:
        return None
    ta, tb = t
    ba, bb = b
    d2 = (ba - ta) ** 2 + (bb - tb) ** 2
    if d2 < 1.0:
        return None
    lo = max(0, j0 - 3)
    hi = min(NSTRIP, j0 + 4)
    vals = [((prof[j][1] - ta) ** 2 + (prof[j][2] - tb) ** 2)
            - ((prof[j][1] - ba) ** 2 + (prof[j][2] - bb) ** 2)
            for j in range(lo, hi)]
    sv = smooth3(vals)                    # 与粗定位同一套平滑（浅色差，见 smooth3）
    sub = [(prof[lo + k][0], sv[k]) for k in range(len(sv))]
    sub_dead = [dead[j] for j in range(lo, hi)] if dead is not None else None
    return cross_row(sub, 0.0, CROSS_MIN_SWING_FRAC * 2.0 * d2, sub_dead)


def _five_ok(inl):
    """5 点候选的额外验收（2026-09-29 第十一次）：内点 x 跨度 ≥90px 且 RMS ≤4.0。
    候选下限 6→5 是为救"假丢线"帧（任务F 90-97 帧：5 个真点跨 160px、离真值
    2~7px，被 n≥6 硬门整帧拒掉）；但 n≥6 当年挡的"5 点凑垃圾线"（实测能差 8.6°）
    得有新闸 —— 跨度防"挤在一小段"、RMS 防"散点连线"。只影响 5 点候选帧，
    ≥6 点路径与旧版完全一致。
    跨度 120→90（第十五次，2026-10-01）：MEAS_X 收窄为 (50,270) 后 8 列全跨只有
    193px，120 的相对严度大增 —— 任务B 124-135 帧真边界贴底只活 5 列（跨 110px、
    近共线 RMS~1.5）被硬杀成丢线。90 ≈ 全跨的一半，仍挡"挤在一小段"。"""
    xs = [p[0] for p in inl]
    if max(xs) - min(xs) < 90.0:
        return False
    f = lsq(inl)
    return f is not None and f[2] <= 4.0


def robust_fit(pts):
    """抗离群拟合：穷举 RANSAC —— 所有点对连成线，取"内点数最多"的那条，
    再用内点做 LSQ 精修、并按同一门槛复筛一次。8 列只有 28 对，开销可忽略。
    返回 (斜率, 截距, RMS, 保留点数, 剔除点数)；点数不够返回 None。
    候选下限 6→5（2026-09-29 第十一次）：5 点候选须另过 _five_ok 双闸。"""
    n = len(pts)
    if n < 5:                      # 6→5：救"5 真点"帧；垃圾线风险由 _five_ok 挡
        return None
    best = None
    for i in range(n - 1):
        for k in range(i + 1, n):
            dx = pts[k][0] - pts[i][0]
            if dx == 0:
                continue
            m = (pts[k][1] - pts[i][1]) / float(dx)
            c = pts[i][1] - m * pts[i][0]
            inl = [p for p in pts if abs(p[1] - (m * p[0] + c)) <= RANSAC_TOL_PX]
            if best is None or len(inl) > len(best):
                best = inl
    if best is None or len(best) < 5:
        return None
    if len(best) == 5 and not _five_ok(best):
        return None
    f = lsq(best)
    if f is None:
        return None
    m2, c2 = f[0], f[1]
    inl2 = [p for p in pts if abs(p[1] - (m2 * p[0] + c2)) <= RANSAC_TOL_PX]
    if len(inl2) >= 5:
        if len(inl2) > 5 or _five_ok(inl2):
            f2 = lsq(inl2)
            if f2 is not None:
                return f2[0], f2[1], f2[2], len(inl2), n - len(inl2)
    return f[0], f[1], f[2], len(best), n - len(best)


