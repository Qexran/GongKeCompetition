                           # 散点是"两跳边之间来回跳"的垃圾，硬拟抛物线 RMS 5~17、
                           # 角度能喷 ±50°；实测 J#145 的 5 内点假抛物线也有 2.45 ——
                           # 真弓形帧（K#58/B#128）RMS ≈1.0，门取 2.0 挡垃圾保真弓


def quad_fit_line(pts):
    """抛物线兜底（第十五次，2026-10-01）：直线 RANSAC 失败但 ≥5 点时的二次拟合。
    背景（任务K/I 实测）：远侧边界在画面里本来就带弓（透视+镜头畸变+真弯），8 列
    穿越排成 U 形 —— 直线怎么拟都不达标 → 整帧丢线，Δ 冻结还把方向标错（K 58-112
    连续 55 帧假丢线）。弓形帧 GT 仍标直线(0)、off 取标注线在控制列的值，抛物线在
    控制列的值与它吻合（K#58 实测 off 误差 0、B#128 误差 2）。
    做法：3 点采样穷举 RANSAC（门槛同 robust_fit），内点 ≥5 且 x 跨度 ≥90 且
    RMS ≤ QUAD_RMS_MAX 才认；角度取**近半段**内点的直线斜率（航向跟近段切线，
    与 CURVE_RMS_PX 分支同一哲学 —— U 形在中部的切线≠两端弦，K#58 顶点导数 ~0°
    而近半段斜率 18.6° 与真值 17.5° 吻合），近半段不足 2 点时退回顶点导数。
    返回与 robust_fit 同构的"虚拟直线" (m, c, rms, nk, nd)：c 平移到过
    (CTRL_X, q(CTRL_X))，下游出量/曲线判别/REACQ 验收全部照旧工作。"""
    n = len(pts)
    if n < 5:
        return None
    best = None
    for i in range(n - 2):
        for k in range(i + 1, n - 1):
            for j in range(k + 1, n):
                x1, y1 = pts[i]
                x2, y2 = pts[k]
                x3, y3 = pts[j]
                if x3 == x1:
                    continue
                f12 = (y2 - y1) / float(x2 - x1) if x2 != x1 else 0.0
                f23 = (y3 - y2) / float(x3 - x2) if x3 != x2 else 0.0
                a = (f23 - f12) / (x3 - x1)
                b = f12 - a * (x1 + x2)
                c = y1 - a * x1 * x1 - b * x1
                inl = [p for p in pts
                       if abs(p[1] - (a * p[0] * p[0] + b * p[0] + c)) <= RANSAC_TOL_PX]
                if best is None or len(inl) > len(best):
                    best = inl
    if best is None or len(best) < 5:
        return None
    xs = [p[0] for p in best]
    if max(xs) - min(xs) < 90.0:
        return None
    # 内点 LSQ 精修（3x3 正规方程，克莱姆法则，n≤8 手算开销可忽略）
    sx = sum(p[0] for p in best); sxx = sum(p[0] * p[0] for p in best)
    sxxx = sum(p[0] ** 3 for p in best); sxxxx = sum(p[0] ** 4 for p in best)
    sy = sum(p[1] for p in best); sxy = sum(p[0] * p[1] for p in best)
    sxxy = sum(p[0] * p[0] * p[1] for p in best)
    A = [[len(best), sx, sxx], [sx, sxx, sxxx], [sxx, sxxx, sxxxx]]
    B = [sy, sxy, sxxy]

    def det3(m):
        return (m[0][0] * (m[1][1] * m[2][2] - m[1][2] * m[2][1])
                - m[0][1] * (m[1][0] * m[2][2] - m[1][2] * m[2][0])
                + m[0][2] * (m[1][0] * m[2][1] - m[1][1] * m[2][0]))
    D = det3(A)
    if abs(D) < 1e-9:
        return None
    A1 = [[B[0], A[0][1], A[0][2]], [B[1], A[1][1], A[1][2]], [B[2], A[2][1], A[2][2]]]
    A2 = [[A[0][0], B[0], A[0][2]], [A[1][0], B[1], A[1][2]], [A[2][0], B[2], A[2][2]]]
    A3 = [[A[0][0], A[0][1], B[0]], [A[1][0], A[1][1], B[1]], [A[2][0], A[2][1], B[2]]]
    c = det3(A1) / D
    b = det3(A2) / D
    a = det3(A3) / D
    e = math.sqrt(sum((p[1] - (a * p[0] * p[0] + b * p[0] + c)) ** 2 for p in best) / len(best))
    if e > QUAD_RMS_MAX:
        return None
    near = [p for p in best if p[1] > NEAR_HALF_ROW]
    m = None
    if len(near) >= 2:
        f = lsq(near)
        if f is not None:
            m = f[0]
    if m is None:
        m = 2.0 * a * CTRL_X + b        # 顶点导数兜底
    row_c = a * CTRL_X * CTRL_X + b * CTRL_X + c
    return m, row_c - m * CTRL_X, e, len(best), n - len(best)


def black_row(prof, near):
    """色阶行附近 ±3 条里找 L 最小的那条（练习地图的黑线），抛物线插值取行。"""
    k = int((near - WIN_Y[0]) / STRIP)
    lo, hi = max(0, k - 3), min(len(prof), k + 4)
    bi, best = None, None
    for j in range(lo, hi):
        if best is None or prof[j][3] < best:   # 剖面改成 (y,a,b,L) 四元组，L 在第 3 列
            best, bi = prof[j][3], j
    if bi is None or best > BLACK_MAX_L:
        return None
    if 0 < bi < len(prof) - 1:
        l, c, r = prof[bi - 1][3], prof[bi][3], prof[bi + 1][3]
        if c > l - BLACK_MIN_DIP or c > r - BLACK_MIN_DIP:
            return None                      # 不够"暗下去"→ 不是黑线
        d = l - 2 * c + r
        if d > 0:
            off = 0.5 * (l - r) / d
            if -1.0 <= off <= 1.0:
                return prof[bi][0] + off * STRIP
    return prof[bi][0]


def column_crossing(prof, margin):
    """单列完整裁决（2026-09-29 第十一次抽成纯函数）—— 主循环/回放器/平台三方调用
    同一份：此前 Replay.step 手工复刻第 3 步，第八/十次机制漏同步，离线结论不再代表
    相机（RECOVERY_NOTE.md 根因4）。步骤 = 亮度掩码 → 亮条参考色 → f 距离剖面
    （smooth3）→ cross_row → refine_local → 穿越合法域闸。
    prof: col_profile 剖面 [(行中心, a, b, L), ...]；margin: 全局两侧色心距（落差闸
    的满程下限）。返回 (row, ta, tb, ba, bb)：
      整体 None      亮条凑不齐 = 整列在补光死角里，不采；
      row=None       该列无合法穿越（参考色照常返回，供全局中位数覆盖用）。
    亮度掩码（第八次）：补光死角 L 塌向 0 时 |a|,|b| 一起塌 —— 黑条会染黑参考色、
    黑↔亮过渡会造假穿越。判暗 = L < max(L_DARK_ABS, DARK_FRAC×近端亮度)；从窗口顶
    连下来的暗条串（dead）里的穿越一律不认。顶参考 = 从上往下前 2 条亮条（整列搜，
    3→2 给贴黑区下缘的薄亮带真交界留空间；黑区深达 ~100 行时死写窗口会一列全丢）。
    底参考 = 从最底亮条向上**区域生长**（第十一次）：与最底那条比 (a,b) 色距
    ≤ REF_GROW_STEP 才收、超距即停 —— 渐变沿程漂移，锚死最底亮条参考带才贴得住实色。
    合法域闸（第十次立、第十一次改）：
      A = 穿越必须落在顶参考带之下（row ≥ top_lim；带内 = 上下是同一条渐变）。
          ⚠️ 旧 bot_lim（穿越不得低于底参考带）已删 —— 任务F 22-24/31-34 帧"贴底
          交界"被它连真带假全杀；带内防假改由底参考生长保住。
      B = 带间 f 不得回翻错侧超满程 15%（真两面在穿越两侧饱和，渐变一路漂移必回翻）。"""
    n = len(prof)
    l_near = (prof[-1][3] + prof[-2][3] + prof[-3][3]) / 3.0
    thr = max(L_DARK_ABS, DARK_FRAC * l_near)
    dark = [p[3] < thr for p in prof]
    ndead = 0                           # 从窗口顶连下来的暗条数（黑区本体）
    for dd in dark:
        if not dd:
            break
        ndead += 1
    dead = [j < ndead for j in range(n)]
    tj = [j for j in range(n) if not dark[j]][:2]
    bj = []
    for j in range(n - 1, n - 9, -1):   # 底部 9 条窗口（与旧版同）
        if len(bj) >= 3:
            break
        if dark[j]:
            continue
        if not bj:
            bj.append(j)                # 锚 = 最底亮条
            continue
        if ((prof[j][1] - prof[bj[0]][1]) ** 2
                + (prof[j][2] - prof[bj[0]][2]) ** 2) > REF_GROW_STEP * REF_GROW_STEP:
            break                       # 渐变漂出锚条色距 → 生长到头
        bj.append(j)
    if len(tj) < 2 or len(bj) < 2:
        return None
    ta = sum(prof[j][1] for j in tj) / len(tj)
    tb = sum(prof[j][2] for j in tj) / len(tj)
    ba = sum(prof[j][1] for j in bj) / len(bj)
    bb = sum(prof[j][2] for j in bj) / len(bj)
    da, db = ba - ta, bb - tb
    d2 = da * da + db * db              # 该列两侧参考色距离² ≈ f 满程的一半
    f = [((p[1] - ta) ** 2 + (p[2] - tb) ** 2)
         - ((p[1] - ba) ** 2 + (p[2] - bb) ** 2) for p in prof]
    fs = smooth3(f)                     # 浅色差：先平滑再找过零（见 smooth3）
    # 落差闸满程估计 = max(2×该列参考距², margin²)：margin² 是绝对下限，整列都在
    # 一侧时 d2 会很小，不能被噪声糊过去；只当保守一半用（真实满程 ≥ 2×margin²），
    # 直接当满程会把 LED 热点列（参考距偏小）的好点误杀（uuu.bmp 实测差 8%）
    row = cross_row([(prof[j][0], fs[j]) for j in range(n)], 0.0,
                    CROSS_MIN_SWING_FRAC * max(2.0 * d2, margin * margin), dead)
    # 第二遍：局部参考色细化（见 refine_local）。粗定位失败（阴影边假点）的列不救；
    # 这里只修"真交界上的过零点被参考色横漂带拱"。第十三次起**迭代收敛**：局部
    # 参考的照度差随迭代减半、偏差几何收敛，3 次即到不动点（见 REFINE_ITERS 注释）
    # —— 单次细化会把过零留在列内照度梯度的中点（暗列尤其狠：补光中心散开，
    # 边缘列的暗路面"看起来像顶参考"，过零被往下推几十 px）。
    for _ in range(REFINE_ITERS):
        if row is None:
            break
        r2 = refine_local(prof, row, dark, dead)
        if r2 is None or abs(r2 - row) < 1.0:
            if r2 is not None:
                row = r2
            break
        row = r2
    if row is not None:
        top_lim = WIN_Y[0] + (tj[-1] + 1) * STRIP
        bad = row < top_lim             # 闸A：穿越不得落进顶参考带（只留顶侧）
        if not bad:
            eps = 0.3 * d2              # 满程 2·d2 的 15%
            for j in range(tj[-1] + 1, min(bj)):
                if dead[j] or abs(prof[j][0] - row) < 0.75 * STRIP:
                    continue            # 黑区条不判；穿越 ±1 条是过渡带不判
                if ((prof[j][0] < row and fs[j] > eps)
                        or (prof[j][0] > row and fs[j] < -eps)):
                    bad = True          # 闸B：带间回翻错侧 → 渐变假穿越
                    break
        if bad:
            row = None
    return (row, ta, tb, ba, bb)


# ---------------- 丢线分类（state 2/3/4）：参考色 + 两级判据 ----------------
