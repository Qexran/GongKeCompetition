ref_bnd  = None             # (a, b) 边界区参考色（上带 EMA）；None = 还没见过有效帧
ref_road = None             # (a, b) 路面参考色（下带 EMA）


def ema_ref(old, new):
    if old is None:
        return new
    k = LOST_EMA
    return (old[0] + (new[0] - old[0]) * k, old[1] + (new[1] - old[1]) * k)


def chrom_d(p, r):
    da = p[0] - r[0]
    db = p[1] - r[1]
    return math.sqrt(da * da + db * db)


def classify_lost(pts, a_up, b_up, a_dn, b_dn):
    """丢线帧判"车往哪面塌陷" → 3（黄区侧/压黄区）/2（路面灰侧/压灰区）/4（说不清）。
    主判据（2026-09-27 用户定律·趋势版）：Δ = 丢线时冻结的 off − 直线基线：
      跌落（Δ < −DELTA_GATE）= 往灰区塌陷 → 2；抬升（Δ > +DELTA_GATE）= 往黄区
      塌陷 → 3；|Δ| 小 = 突然丢（路口/突变）→ 落到备胎证据。
    基线 = 直线帧里慢速跟踪的 offset（偏出 BASE_GATE 即冻结，不被慢速压线拖走；
    自动对准实际工作点，树莓派 SETPOINT 偏置/标定偏差都吸收）。**两个操作数在丢线
    瞬间都已冻结 → Δ 在整段丢线期内恒定** —— 前几版标签跳变的根源就是不同证据源
    在退化帧里轮流发言，此判据从构造上杜绝。
    备胎（基线还没有/|Δ|在门内时才用）：① ≥2 个零星点的中位行（FAR_ROW/NEAR_ROW，
    单点不算）→ ③ 两带颜色对参考色投票（同面才认）→ ④ 4（保持）。
    参考色只在交界居中 REF_SAFE_ROW 的健康帧里刷新（防污染，见主循环第 5 步）。
    树莓派恢复锚点：st=3（黄侧，off 相对基线抬升）→ 让 off 减小；st=2 → 让 off 增大。"""
    global lost_near
    lost_near = '?'
    # ---- ②主判据：Δ = 冻结的 off − 直线基线（整段丢线期恒定）----
    if base_off is not None and last_offset is not None:
        dlt = last_offset - base_off
        if dlt < -DELTA_GATE:
            lost_near = '灰'
            return 2
        if dlt > DELTA_GATE:
            lost_near = '黄'
            return 3
    # ---- ①备胎：零星交界点的行位置（基线还没有时用）----
    if pts is not None and len(pts) >= 2:
        rows = sorted(p[1] for p in pts)
        med = rows[len(rows) // 2]
        # 行连续门（第十五次，见 ROW_VOTE_BAND）：D 59-64 的过曝雾带假点（行~100，
        # 真边界 ~215）会把行票带偏成"灰"。中位行离丢线前边界行太远 = 假点证据，
        # 弃行票落到颜色票/④。丢线前行位置未知（冷启动）时不设闸。
        if last_row_ctrl is not None and abs(med - last_row_ctrl) > ROW_VOTE_BAND:
            med = None
        if med is not None:
            if med < FAR_ROW:               # 边界在画面上半 = 车往灰侧偏
                lost_near = '灰'
                return 2
            if med > NEAR_ROW:              # 下半 = 压向黄区
                lost_near = '黄'
                return 3
    # ---- ③备胎：两带颜色投票 ----
    if ref_bnd is not None and ref_road is not None:
        d_ut, d_ur = chrom_d((a_up, b_up), ref_bnd), chrom_d((a_up, b_up), ref_road)
        d_dt, d_dr = chrom_d((a_dn, b_dn), ref_bnd), chrom_d((a_dn, b_dn), ref_road)
        if (min(d_ut, d_ur) <= LOST_CLASS_GATE
                and min(d_dt, d_dr) <= LOST_CLASS_GATE):
            top_y = d_ut <= d_ur
            if top_y == (d_dt <= d_dr):
                lost_near = '黄' if top_y else '灰'
                return 3 if top_y else 2
    return 4                        # |Δ|在门内且备胎也没证据：突然丢，保持


