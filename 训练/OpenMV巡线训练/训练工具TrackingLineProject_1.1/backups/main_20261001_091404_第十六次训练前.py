# ==================== 测量核心 ====================
# 思路：逐列把测量区切成横条，用 get_statistics 取每条的 (a,b,L) **均值**，算各条到
# 该列"上/下参考色"的距离²之差 f，找 f 过零的那一行（相邻条线性插值），再对 8 个点
# 做抗离群拟合。2026-09-25 前是"单判别通道穿过两侧色心中点"，弃用原因见主循环第 3 步。
# 这里的 API 都是本机实测通过的：snapshot / lens_corr / get_statistics / draw_*
