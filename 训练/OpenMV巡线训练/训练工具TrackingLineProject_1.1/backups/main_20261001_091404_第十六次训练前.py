    img = img.lens_corr(strength=LENS_CORR_STRENGTH)   # 镜头畸变校正

    # valid=0 时沿用上一帧（丢线策略在树莓派侧）
    valid   = False
    offset  = last_offset
    angle   = last_angle
    state_v = 4            # 默认"方向不明"; 下面各步给出更准的值, 出错也落在这里
    lost_near = '?'        # 所在面也每帧重置（防上一帧的值漏到出错帧）
    stage   = '0'
    src_ch  = '-'

    try:
        # ---- 1) 两侧色心：用中位数（对"交界跑进色心带"这种污染不敏感）----
        stage = '1 色心'
        su = img.get_statistics(roi=TOP_BAND)
        sd = img.get_statistics(roi=BOT_BAND)
        a_up, b_up = sval(su, 'a_median', 'a_mean'), sval(su, 'b_median', 'b_mean')
        a_dn, b_dn = sval(sd, 'a_median', 'a_mean'), sval(sd, 'b_median', 'b_mean')
        l_up = sval(su, 'l_median', 'l_mean')
        l_dn = sval(sd, 'l_median', 'l_mean')
        margin = max(abs(a_up - a_dn), abs(b_up - b_dn))

        # ---- 2) 自动选判别通道：a 和 b 里分得更开的那个 ----
        stage = '2 通道'
        is_a = abs(a_up - a_dn) >= abs(b_up - b_dn)
        ch = 'a' if is_a else 'b'
        # 有效条件：两侧确实分得开（"全灰/全黄"时 margin 会塌掉）
        enough = margin >= MARGIN_MIN

        # ---- 3) 逐列取剖面 → 找交界行 ----
        # 判别量（2026-09-25 起）：每条横条的 (a,b) 到"上参考色"和"下参考色"的距离²
        # 之差 f，f<0 离上侧近、f>0 离下侧近，过零即交界。
        # 为什么弃掉"单通道过中点"：固定曝光下阴影=欠曝，L 和 |a|,|b| 一起塌向 0，
        # 黑条也是 0 —— 单通道剖面里"阴影边"和"真边界"是同一种特征，落差大的那个赢，
        # 就锁错（uuu.bmp 帧实证：x≈180 锁到褶皱阴影边、x≈20/300 锁到黑条下沿）。
        # 距离剖面下，阴影/褶皱只是把色点往原点压：下侧饱和、上侧弱色时，压向黑的点
        # 仍离上侧参考近 → 阴影边不过零；色→黑→色的 f 全程单调，落差不再被劈成两半。
        # 且 f 不再有 own_mid 这个可漂移的标量中点 —— 判别面是上下参考色连线的中垂面，
        # own_mid 被 LED 热点/阴影推着跑而让褶皱边翻面的失效模式整个不存在了。
        stage = '3 逐列'
        # 逐列裁决已抽成纯函数 column_crossing（2026-09-29 第十一次）：亮度掩码、
        # 亮条参考色（顶 2 条 / 底部区域生长 REF_GROW_STEP）、f 距离剖面、
        # refine_local、合法域闸 A/B 全在函数里 —— 主循环/回放器/平台三方调用
        # 同一份，回放器不再手工复刻第 3 步（第八/十次机制漏同步、离线结论失真
        # 的教训）。返回 (row, ta, tb, ba, bb)：亮条凑不齐 = None 整列不采；
        # row=None = 无合法穿越但参考色照常返回（供下方中位数覆盖用）。
        pts, bpts, tops, bots = [], [], [], []
        for i in range(NCOL):
            x = int(WIN_X[0] + (WIN_X[1] - WIN_X[0]) * (i + 0.5) / NCOL)
            prof = col_profile(img, x)
            res = column_crossing(prof, margin)
            if res is None:
                continue
            row, ta, tb, ba, bb = res
            tops.append((ta, tb))
            bots.append((ba, bb))
            if row is not None and WIN_Y[0] <= row <= WIN_Y[1]:
                pts.append((x, row))
                if CHECK_BLACK:
                    brow = black_row(prof, row)
                    if brow is not None and WIN_Y[0] <= brow <= WIN_Y[1]:
                        bpts.append((x, brow))

        # 全局两侧色/判别通道改用亮条参考色的中位数：TOP_BAND/BOT_BAND 整带统计
        # 吃进黑区后 margin 会塌 → valid 无故翻 0（出量保持上一帧，看起来也像
        # 跳变）；丢线颜色票的参考色同样被带偏。亮列不足 3 个时保留整带统计兜底。
        if len(tops) >= 3:
            a_up = sorted(t[0] for t in tops)[len(tops) // 2]
            b_up = sorted(t[1] for t in tops)[len(tops) // 2]
            a_dn = sorted(t[0] for t in bots)[len(bots) // 2]
            b_dn = sorted(t[1] for t in bots)[len(bots) // 2]
            margin = max(abs(a_up - a_dn), abs(b_up - b_dn))
            ch = 'a' if abs(a_up - a_dn) >= abs(b_up - b_dn) else 'b'
            enough = margin >= MARGIN_MIN

        # ---- 4) 抗离群拟合（丢线期先过 REACQ 点级过滤，见 REACQ_* 常量注释）----
        # 点级过滤 vs 帧级：帧级"拟合出行不符就拒"已实测死锁 —— 假线与真边界并存时
        # RANSAC 选假线→被拒→永远重锁不上；点级先把出画方向对侧的候选滤掉再拟合，
        # 真交界回画必落入边半场，拟合成功即自然解锁。连丢满 REACQ_GATE_FRAMES 帧
        # 熔断放行（fail-open）—— 放行后的再锁定在第 5 步做 Δ 同侧验收（第十二次）。
        stage = '4 拟合'
        pts_fit = pts
        if lost_run > 0 and lost_dir is not None and lost_run < REACQ_GATE_FRAMES:
            if lost_dir == 3:      # 从底出画 → 重锁只认窗口下部（行 ≥ REACQ_ROW_MIN）
                pts_fit = [p for p in pts if p[1] >= REACQ_ROW_MIN]
            else:                  # 从顶出画 → 重锁只认窗口上部（行 ≤ REACQ_ROW_MAX）
                pts_fit = [p for p in pts if p[1] <= REACQ_ROW_MAX]
        fa = robust_fit(pts_fit)
        quad_hold = False
        if fa is None and len(pts_fit) >= 5:
            fq = quad_fit_line(pts_fit)   # 弓形边界兜底（第十五次，见 quad_fit_line）
            if fq is not None:
                fa = fq[:5]
                quad_hold = True
        fb = robust_fit(bpts) if CHECK_BLACK else None

        # ---- 5) 出量：来源可选(黑线/色边)，量出后再过 中数3+EMA ----
        # 黑线行定义=黑条中心（L 极小处），比色边的"蓝侧边缘"高 ~5px —— 换源后
        # TARGET_OFFSET 要按老流程重标。滤波只动出量：EMA 压"内点集翻动"的持续台阶
        # 和逐帧噪声；中数默认关（这里的跳变是双稳态翻动不是尖刺，见 FILT_MED_N）。
        # invalid 帧不入队不推进 EMA —— 树莓派拿到的仍是上一拍值，与"valid=0 沿用
        # 上一帧"的旧协议语义一致。
        stage = '5 出量'
        reacq_reject = False          # 放行期再锁定的 Δ 同侧验收结果（见 raw_off 处）
        if fa and enough:
            if USE_BLACK_PRIMARY and fb is not None and fb[2] <= BLACK_RMS_MAX:
                fit, src_pts, src_ch = fb, bpts, 'B'
            else:
                fit, src_pts, src_ch = fa, pts, 'C'
            # 曲线判别要用**全局**拟合的 RMS（state 1 的依据）：近段重拟合成功后 RMS
            # 会降回来，但"这窗里是路口大弧"的事实没变 —— 树莓派侧 state=1 的语义
            # 是"这帧来自路口/弯道"，不是"拟合质量差"。
            is_curve = fit[2] > CURVE_RMS_PX
            if is_curve:
                # 交界在这窗里是条弧（路口/弯道/过坎后车头随机歪）。航向该跟**车马上
                # 要进的近段**切线，不是整条弧的平均切线（平均会同时把 angle 和
                # offset 带偏）。取全局拟合内点里靠车这半边（行 > 测量窗中线）重拟合;
                # 近段凑不够 4 点或没更直就保留全局拟合（尽力而为）。
                near = [p for p in src_pts
                        if p[1] > NEAR_HALF_ROW
                        and abs(p[1] - (fit[0] * p[0] + fit[1])) <= RANSAC_TOL_PX]
                if len(near) >= 4:
                    fn = lsq(near)
                    if fn is not None and fn[2] < fit[2]:
                        fit = (fn[0], fn[1], fn[2], len(near), len(src_pts) - len(near))
            m, c, e, nk, nd = fit
            lat_span = FRAME_H
            row_ctrl = m * CTRL_X + c                      # 控制列处的交界行
            # 夹回测量窗：直线行跑不出去；曲线帧近段切线外推到控制列可能甩出窗外，
            # 不夹会把虚大的满偏 offset 交给树莓派 —— 方向不会错，大小会虚。
            if row_ctrl < WIN_Y[0]:
                row_ctrl = WIN_Y[0]
            elif row_ctrl > WIN_Y[1]:
                row_ctrl = WIN_Y[1]
            error_px = (row_ctrl - lat_span / 2.0) - TARGET_OFFSET
            raw_off = max(-100, min(100, int(error_px / lat_span * 2 * ERR_GAIN)))
            raw_ang = max(-900, min(900, int(math.degrees(math.atan(m)) * 10)))
            if quad_hold:
                # 弓形帧角度保持（第十五次）：抛物线的近段切线是 U 形顶点局部斜率，
                # 与 GT 弦线差可达 13°（K#58 实测），且弦↔切切换本身就是一次大突跳
                # —— 角度稳定性优先，保持上一拍输出角；off 照常（抛物线在控制列的
                # 值与真值吻合，K#58/B#128 实测误差 0~2）。恒定光照下车在动，几帧内
                # 线拟合会接管回来。
                raw_ang = int(filt_a)
            # 放行期再锁定验收（第十二次，第十五次加质量豁免）：丢线满
            # REACQ_GATE_FRAMES 帧后点级过滤放行（fail-open），但锁到的线必须与
            # Δ 判据同侧 —— st=3（往黄区塌陷）期间真交界只能在基线黄侧，锁到
            # raw_off ≤ base_off + DELTA_GATE = 交界"瞬移"到基线另一侧 = 同材渐变
            # 假线（任务P 实测：丢满 8 帧假线当帧假重锁，off 还给成负值）。拒绝并
            # 按丢线处理。只验收放行帧：过滤帧的点已在入边半场，不再二道拒。
            # 质量豁免（第十五次）：内点 ≥REACQ_QA_NK 且 RMS ≤REACQ_QA_RMS 的高
            # 质量拟合不受陈旧 Δ 方向否决 —— 边界扫掠回窗内时（车在丢线期继续动），
            # 真边界会越过基线到另一侧，A 114-134 被旧验收整段拒成 21 帧盲。
            if lost_run >= REACQ_GATE_FRAMES and lost_dir is not None \
                    and base_off is not None:
                qa_ok = nk >= REACQ_QA_NK and e <= REACQ_QA_RMS
                if lost_dir == 3 and raw_off <= base_off + DELTA_GATE and not qa_ok:
                    reacq_reject = True
                elif lost_dir == 2 and raw_off >= base_off - DELTA_GATE and not qa_ok:
                    reacq_reject = True
            if not reacq_reject:

                filt_buf_o.append(raw_off)
                filt_buf_a.append(raw_ang)
                if len(filt_buf_o) > FILT_MED_N:
                    del filt_buf_o[0]
                    del filt_buf_a[0]
                med_o = sorted(filt_buf_o)[len(filt_buf_o) // 2]
                med_a = sorted(filt_buf_a)[len(filt_buf_a) // 2]
                if filt_init:
                    filt_o, filt_a = float(med_o), float(med_a)
                    filt_init = False
                else:
                    # 门控 EMA（2026-09-29 第十一次）：两轴各自判门 —— 台阶在门内是
                    # 噪声/内点集翻动（慢平滑压住），门外是真运动/重锁（快跟防拖影）。
                    # 检验只看 /compare 残差 std，勿用 MAE（见 CLAUDE.md 抖动指标段）
                    a_o = FILT_EMA_A if abs(med_o - filt_o) <= FILT_FAST_GATE else FILT_EMA_A_FAST
                    a_a = FILT_EMA_A if abs(med_a - filt_a) <= FILT_FAST_GATE else FILT_EMA_A_FAST
                    filt_o += a_o * (med_o - filt_o)
                    prev_a = filt_a
                    filt_a += a_a * (med_a - filt_a)
                    # 角度限速（第十五次，见 ANG_RATE_MAX 注释）：真坡不削、只削尖刺
                    if filt_a - prev_a > ANG_RATE_MAX * 10.0:
                        filt_a = prev_a + ANG_RATE_MAX * 10.0
                    elif prev_a - filt_a > ANG_RATE_MAX * 10.0:
                        filt_a = prev_a - ANG_RATE_MAX * 10.0
                offset = int(filt_o)
                angle = int(filt_a)

                valid = True
                state_v = 1 if is_curve else 0
                # 有效帧刷新两侧参考色 —— 但只在交界行舒服地待在窗口中部（REF_SAFE_ROW）
                # 时刷：边界行贴近下带(>195)时底带已被黄区吃进、贴上带(<70)时顶带已被路面
                # 吃进，这种帧刷参考色会把参考污染成对面（2026-09-27 修的翻车：压黄过程
                # 中 ref_road 被一路带成黄 → 全黄帧两票打架 → 落兜底错报"边界远出"）。
                if REF_SAFE_ROW[0] <= row_ctrl <= REF_SAFE_ROW[1]:
                    ref_bnd = ema_ref(ref_bnd, (a_up, b_up))
                    ref_road = ema_ref(ref_road, (a_dn, b_dn))
                # 直线基线（丢线判据 Δ 的基准，用户定律·趋势版）：只在"直线"帧里慢跟踪，
                # 偏出 BASE_GATE 即冻结 —— 慢速压线不会把基线拖走，路口弧(st=1)也不参与。
                # 它自动对准实际工作点（树莓派 SETPOINT 偏置/标定偏差都吸收掉）。
                if state_v == 0:
                    if base_off is None:
                        base_off = float(offset)
                    elif abs(offset - base_off) <= BASE_GATE:
                        base_off += BASE_RATE * (offset - base_off)
                lost_run = 0                  # 重锁成功：REACQ 点级过滤计数/方向复位
                lost_dir = None
                last_row_ctrl = row_ctrl      # 备胎点票/时序参考
                last_offset = offset
                last_angle = angle
        if (not (fa and enough)) or reacq_reject:
            # 丢线（含熔断重试被拒帧）：offset/angle 沿用上一帧（协议语义），
            # state 报丢线方向 —— 树莓派按它定向找线，取代它那边死写的固定方向
            state_v = classify_lost(pts, a_up, b_up, a_dn, b_dn)
            lost_run += 1
            if lost_dir is None and state_v in (2, 3):
                # 方向只在"Δ 判据给的"时才 arm REACQ 过滤（Δ 整段恒定，可信）；
                # 备胎证据（零星点票/颜色票）不 arm —— 可能只是假点的行位置
                dlt = (last_offset - base_off) if base_off is not None else None
                if dlt is not None and ((dlt < -DELTA_GATE and state_v == 2)
                                        or (dlt > DELTA_GATE and state_v == 3)):
                    lost_dir = state_v

        # ---- 6) 可视化（调试用，不影响出量）----
        if DRAW:
            try:
                d_rect(img, TOP_BAND, (0, 255, 255))
                d_rect(img, BOT_BAND, (0, 255, 255))
                d_line(img, (WIN_X[0], WIN_Y[0], WIN_X[1], WIN_Y[0]), (0, 255, 255))
                for p in pts:
                    d_cross(img, p[0], int(p[1]), (255, 255, 0), 4)
                for p in bpts:
                    d_cross(img, p[0], int(p[1]), (255, 0, 0), 2)
                if fa:
                    d_line(img, (WIN_X[0], int(fa[0] * WIN_X[0] + fa[1]), WIN_X[1],
                                 int(fa[0] * WIN_X[1] + fa[1])), (0, 255, 0))
            except Exception as de:
                print("[巡线] 绘制失败(不再尝试):", de)
                DRAW = False

        # ---- 6.5) 拍照（收到 'P' 时把**刚测过的这一帧**存到相机盘）----
        #    放在绘制之后: 存下来的照片与 IDE 里看到的一致（带黄十字/绿拟合线）,
        #    "当时每列读到什么"一眼可见 —— 这正是不对劲时最想留的证据。
        #    想要干净原图, 把这三行挪到第 6 步之前即可（位置就是开关）。
        #    ⚠️ photo.take 自己吞掉所有异常, 存图失败不会影响本帧出量。
        if want_photo:
            want_photo = False
            if photo is not None:
                photo.take(img)
            else:
                print("[拍照] photo 模块不可用, 忽略本次 'P'")

        # ---- 7) 状态输出（限速；只在 SENDING 之外也打，方便台架上不上位机时看）----
        #      有效帧带侧别（|Δ|>门 时 [直线·黄]/[直线·灰]）—— 深偏帧只打[直线]会被
        #      误读成"正常巡线"（2026-09-27 第七次：用户看"直线-98→回升-59→判灰"以为
        #      矛盾，其实是灰侧深处的回移）。丢线帧加打 d=<Δ>，判据依据一眼可见。
        if time.time() - last_print > PRINT_EVERY_S:
            last_print = time.time()
            cur = offset if valid else last_offset
            d_show = (cur - base_off) if base_off is not None else None
            if valid:
                if state_v == 1:
                    st_txt = '路口弧'
                elif d_show is not None and d_show > DELTA_GATE:
                    st_txt = '直线·黄'
                elif d_show is not None and d_show < -DELTA_GATE:
                    st_txt = '直线·灰'
                else:
                    st_txt = '直线'
            elif state_v == 3:
                st_txt = '压黄区'
            elif state_v == 2:
                st_txt = '压灰区'
            else:
                st_txt = '不明'
            msg = "valid=%d[%s] off=%4d ang=%+6.1f st=%d" % (
                1 if valid else 0, st_txt, offset, angle / 10.0, state_v)
            if (not valid) and d_show is not None:
                msg += " d=%+d" % int(d_show)   # 丢线判据 Δ（冻结 off − 直线基线）
            msg += " 点%d剔%d 列%d/%d 通道%c 距%.0f %.0ffps" % (
                fa[3] if fa else 0, fa[4] if fa else 0, len(pts), NCOL,
                ch, margin, clock.fps())
            if fb:
                msg += " |黑线%+6.1f" % math.degrees(math.atan(fb[0]))
            msg += " 出%c" % src_ch
            print(msg)

    except Exception as ex:
        print("[巡线] 出错 @%s: %s" % (stage, ex))
        try:
            sys.print_exception(ex)
        except Exception:
            pass
        valid = False                    # 出错也要继续发帧（valid=0），别让链路哑掉

    # ---- 8) 串口输出（文本帧，树莓派端 openmv_serial.py 解析）----
    #    格式: L,<offset>,<angle>,<valid>,<state>\r\n   —— 仅 SENDING 时发送
    #    ⚠️ 树莓派端须先部署"4/5 字段都收"的解析器（方案 Part 3），旧解析器会把
    #    5 字段帧整行拒收 → 数据永远陈旧。部署顺序：先 Pi 后相机盘。
    if SENDING:
        uart.write("L,%d,%d,%d,%d\r\n" % (offset, angle, 1 if valid else 0, state_v))
