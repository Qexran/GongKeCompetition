/* ⚠️ **为什么是 P 环 + 三道阻尼, 刻意不做 I/D**: 靶静止、无负载扰动, P 到死区即收敛。
 *    迟延链 ~150-200ms（采集 + 处理 + 串口 + 节拍）, Kp 直接沿用 0.04°/px 起步即可;
 *    三道阻尼分别是 —— 单拍限幅（TARGET_SERVO_STEP_DEG）、收敛阈值（CONV_PX）、
 *    连续拍数（CONV_TICKS）。振荡时降 KP_SCALE, 别去动那套共用的 tg 标定。
 * ⚠️⚠️ **`CTRL_MS` 必须 > `MOVE_MS`，差值就是"停稳段"**（2026-09-20 台架实测后的修正）。
 *    「走 N ms → **停** → 采帧 → 下一拍」里那个**"停"不是自动的**：
 *    `vTaskDelay(CTRL_MS)` 之后立刻读的是**最新一帧**，而那一帧是相机在舵机**运动过程中**
 *    采的（Pi 那边还要 ~45ms 处理 + 串口）。CTRL_MS == MOVE_MS 时舵机刚停、
 *    采到的却全是运动中的画面 —— **等于没有"停"这一步**。
 *    实测症状（台架，初始偏差仅 22px）：偏差反复穿越零点（+22→−42→+65→−29），
 *    幅度一路涨到行程闸；逐拍看"实际移动 ÷ 期望移动"在 **7.0× 与 0.1× 之间乱跳**
 *    （采样落点随机：有时在运动最快的中段、有时在还没起步处）。
 *    ⚠️ 这不是增益问题 —— 增益不对会让这个倍率**一致地**偏离 1，而它是乱跳的。
 *    所以**先查 CTRL_MS/MOVE_MS 的比例，再动 KP_SCALE**。
 *    默认 200/100 = 走 100ms + 停 100ms；想更快就两边一起收（如 160/80），
 *    **别把 CTRL_MS 压到 MOVE_MS 以下或相等**。
 *    代码里 `ulCtrlMs <= ulMoveMs` 时会打一条 `TGTS warn: ctrl<=move no settle` 提醒。
 *    ⚠️ **底盘接管阶段这条纪律不适用**: 那个"停稳"由 `vChassisMoveCameraLateral` 内部的
 *    `fChassisMoveDelay` 阻塞等待提供（位置模式会一直等到估算到位）, 与 MOVE/CTRL 的差值无关。
 *    在底盘阶段照这节的处方去调 CTRL/MOVE 比例是白费功夫 —— 要查就查 PX_TO_MM（过冲/太慢）。
 * ⚠️ Pi 起流后要先做几帧全画面锁定（~0.5-1s）才有流帧, 所以路线里那块的超时默认 6000ms
 *    够覆盖「起流 1s + 收敛 1-2s + 余量」。⚠️ **这个值没有 <8s 的硬约束** ——
 *    流模式下 Pi 心跳照发（跟踪跑在独立线程里, 不像阻塞命令那样断心跳）,
 *    但别配太大, 路线节奏会拖沓。 */

