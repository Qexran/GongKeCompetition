/* ==================== 看路校准（黄区直边方向角 → 航向基准, 2026-10 加） ==================== */
/* 链路: 路线排 STEP_ROAD_YAW_WAIT → ucRpiRoadYaw 发 RPI_TASK_ROAD_YAW("H")
 *   → Pi 回 0x09 帧（**ang = 黄区直边的图像方向角** [0.01°], 见 docs/串口协议.md §6j）
 *   → 本端只发遥测（roadyaw_*）与调试串, **不动车、不改航向** —— 先验证阶段:
 *     现场把 roadyaw_ang / roadyaw_err 与陀螺 yaw 并排记录, 确认相关性之后再接
 *     「yaw_bias += k×err」类的**慢速互补**修正（**别硬置 yaw** —— 会踢到正在
 *     咬航向的巡线闭环, 而且一次坏帧就是一次航向跳变）。
 * ⚠️ 为什么角度能当航向基准: 黄区（比赛黄胶带/练习图米黄篷布）**固定在场上**、相机
 *    **固定在车上** ⇒ 直边在图像里的方向只随**车航向**变（直线方向对平移不敏感）——
 *    与「看路」那两把尺(Δx/Δy 把平移与航向混在一起)互补。err = (实测−理想)×方向
 *    就是「陀螺漂了多少」的现场读数。
 * ⚠️ Pi 侧掩膜**整体复用看路那套**（Y−B 自适应 + ROAD_WARM_*）, 自己的旋钮只有
 *    ROADYAW_ROI_*（人工罩住一段**直边**, 别把拐角/圆弧罩进来）与质量门 —— 见 Pi 仓库
 *    tasks/_road_yaw.py 顶部。窗边框点 Pi 会自动剔（车固连的直线混进拟合 = 测到常数）。
 * 标定顺序: ①车摆**基准停车位**（与看路同一位）→ 蓝牙读 roadyaw_ang 填进 ROADYAW_ANGLE_IDEAL_DEG
 *          → ②原地转个**已知角**（比如支点转 90°）, 看 roadyaw_err 的变化量与方向对不对得上
 *          → 反了翻 ROADYAW_DIR → ③此后 err 就是漂移读数; 台架上先看「静止时 err 是否≈0 且稳」。
 * ⚠️⚠️ **ideal 的未标定哨兵是 |值|>90, 不是 0**（与 road_dx_ideal 那套不同!）:
 *    竖直的直边 ang 本来就 = 0°, 0 是合法值 —— 所以这里默认填 999 逼你先标。
 * ⚠️ 全部量都是蓝牙可改的**运行时量**（「蓝牙」Tab 的「看路校准」组, 零重编译）;
 *    这里改的值只决定**上电初值**。 */
#define ROADYAW_ANGLE_IDEAL_DEG    (90.0f)   /* 基准方向角 [°] @(-90~90, 哨兵999) // 放直时**黄区直边的图像方向角**实测 = **+90**（直边近水平, mod 180 表示下 ±90 同一朝向, err 计算有折回两种写法等价; 按屏显写 90 免得"对不上"）; 换机位/换边 → 蓝牙 roadyaw_ideal 现场改; ⚠️|值|>90 = 未标定（哨兵 999）→ 本步照测照报（不响, 校准流程静音） */
#define ROADYAW_DIR                (-1.0f)   /* 方向 @(-1~1) // err=(实测−理想)×本值; **默认 −1 = 台架实测**（陀螺正漂/正转时相机读数减小: 90→88, err 要乘 −1 才与陀螺同号, 偏置推导才成立）; 现场原地转**已知角**复核, 反了改回 +1; 运时量=蓝牙 roadyaw_dir */
/* ---- 对齐偏置（STEP_ROAD_YAW_WAIT 消费; 2026-10 加）----
 * 每次看路校准都把全场航向零点对到相机基准: bias = wrap180(原始航向 − err) ⇒
 * 发布 yaw ≡ err（**"放直"= 0**）—— 上电摆放误差与累计漂移一次消掉。生效与否由下面的
 * **编译期**开关定 —— 现场不碰蓝牙, 蓝牙只拿来调参数。偏置**易失**: 上电归零
 * （航向零点本来就该每次开机重新定）。⚠️ 世界坐标系不受影响（世界航向记录换算回原始值, 跨校准的残留偏移不错轴）。 */
#define ROADYAW_APPLY_EN           1         /* 发布 yaw 扣漂移偏置 @(0~1) // 1=app_sensors 发布工作航向统一扣 roadyaw_bias（PID/巡线陀螺腿/OLED 全生效）; 0=只算不扣（偏置照样更新进遥测, 台架验证用）。⚠️编译期行为开关（同 ROAD_LED_OFF_EN 的形态）: 上电即生效, 不留运行时开关 —— 偏置上电本来就是 0, 开着也无副作用 */
